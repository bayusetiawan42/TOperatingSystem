[BITS 16]

;Takes the argument 'bx'
PRINT:
	PUSHA
	MOV AH, 0X0E

.PUTCHAR:
	CMP [BX], 0
	JZ .END

	CMP [BX], 0XA
	JE .NEWLINE

	MOV AL, [BX]
	INT 0X10

	INC BX
	JMP .PUTCHAR
.NEWLINE:
	MOV AL, 0XA
	INT 0X10
	MOV AL, 0XD
	INT 0X10

	INC BX
	JMP .PUTCHAR

.END:
	POPA
	RET

;Takes the argument 'dx'
PRINT_WORD:
	PUSHA
	MOV CX, 0
.LOOP:
	CMP CX, 4
	JE .END

	;CONVERT TO ASCII
	MOV AX, DX
	AND AX, 0X000F               ;SET ONLY THE LAST BIT
	ADD AL, 0X30                 ;CONVERT TO ASCII 1-9
	CMP AL, 0X39                 ;IF N > 9  ADD EXTRA 8 TO REPRESENT 'A' - 'F'
	JLE .MODIF_WORD
	ADD AL, 7                    ;ASCII A-Z IS 0X41-0X46. ADDED 7 SO IT BECAME 0X40
.MODIF_WORD:
;REPLACE *BX POSITION WITH ASCII FROM AL
	MOV BX, .HEX_OUT + 5
	SUB BX, CX
	MOV [BX], AL 
	ROR DX, 4           ;SINCE WE JUST KEEP THE LAST BIT
	                    ;SO ROTATE 4 TIMES 0X1234 -> 0X4123 -> 0X3412 -> 0X2341 -> 0X1234

	INC CX
	JMP .LOOP

.END:
	;PRINT FINAL MODIFIED HEX_OUT
	MOV BX, .HEX_OUT
	CALL PRINT

	POPA
	RET

.HEX_OUT:
	DB "0X0000",0

PRINT_NL:
	PUSHA

	MOV AH, 0X0E
	MOV AL, 0XA
	INT 0X10
	MOV AL, 0XD
	INT 0X10

	POPA
	RET
