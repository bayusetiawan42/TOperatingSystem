[BITS 16]
GDT_START:

GDT_NULL:
	DD 0X0000
	DD 0X0000

GDT_CODE:
	DW 0XFFFF
	DW 0X0000
	DB 0X00
	DB 10011010B  ; P=1, DPL=00, S=1, E=1, DC=0, RW=1, A=0
	DB 11001111B  ; G=1, DB=1, L=0, 0,  SEGMENT LIMIT 1111
	DB 0X00

GDT_DATA:
	DW 0XFFFF
	DW 0X0000
	DB 0X00
	DB 10010010B
	DB 11001111B
	DB 0X00

GDT_END:

GDT_DESCRIPTOR:
	DW GDT_END - GDT_START - 1
	DD GDT_START

CODE_SEGMENT EQU GDT_CODE - GDT_START
DATA_SEGMENT EQU GDT_DATA - GDT_START
